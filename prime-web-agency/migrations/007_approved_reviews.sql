-- Additive admin-managed review records. Nothing is public without attribution consent and approval.
BEGIN;
CREATE TABLE IF NOT EXISTS public.approved_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL,
  company_name VARCHAR(160) NOT NULL DEFAULT '',
  quote TEXT NOT NULL,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  attribution_consent BOOLEAN NOT NULL DEFAULT FALSE,
  is_approved BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (NOT is_approved OR attribution_consent)
);
CREATE INDEX IF NOT EXISTS idx_approved_reviews_public ON public.approved_reviews(is_approved,sort_order,id);
COMMIT;
