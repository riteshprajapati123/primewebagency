-- Additive advertisement management records and private media metadata.
BEGIN;
CREATE TABLE IF NOT EXISTS public.advertisements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  ad_type VARCHAR(24) NOT NULL CHECK (ad_type IN ('image','video','animated_text','text_image','text_video','animated_image')),
  headline VARCHAR(240) NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  media_key VARCHAR(80),
  media_mime_type VARCHAR(40),
  media_size INTEGER,
  poster_key VARCHAR(80),
  cta_text VARCHAR(80) NOT NULL DEFAULT '',
  cta_url VARCHAR(2048) NOT NULL DEFAULT '',
  placement VARCHAR(32) NOT NULL CHECK (placement IN ('top_strip','below_hero','above_footer','promo_section')),
  animation VARCHAR(24) NOT NULL DEFAULT 'fade' CHECK (animation IN ('none','fade','slide_up','slide_left','typewriter','reveal','marquee','pulse','zoom')),
  animation_speed NUMERIC(4,2) NOT NULL DEFAULT 1 CHECK (animation_speed BETWEEN 0.25 AND 5),
  text_color VARCHAR(7) NOT NULL DEFAULT '#ffffff',
  background_color VARCHAR(7) NOT NULL DEFAULT '#172554',
  text_align VARCHAR(12) NOT NULL DEFAULT 'center' CHECK (text_align IN ('left','center','right')),
  status VARCHAR(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
  is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  display_order INTEGER NOT NULL DEFAULT 0,
  start_at TIMESTAMPTZ,
  end_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_at IS NULL OR start_at IS NULL OR end_at > start_at)
);
CREATE INDEX IF NOT EXISTS idx_advertisements_public ON public.advertisements(placement,is_enabled,status,display_order);
CREATE TABLE IF NOT EXISTS public.advertisement_media (
  storage_key VARCHAR(80) PRIMARY KEY CHECK (storage_key ~ '^[a-f0-9-]{36}\.(jpg|png|webp|gif|mp4|webm)$'),
  mime_type VARCHAR(40) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm')),
  file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 8388608),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
COMMIT;
