-- Additive media gallery table for the Prime Web Agency admin CMS.
-- Uploaded image bytes live outside the public static directory; this table
-- stores metadata and a generated storage key only.
CREATE TABLE IF NOT EXISTS public.gallery_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    alt_text VARCHAR(300) NOT NULL DEFAULT '',
    category VARCHAR(100) NOT NULL DEFAULT 'General',
    caption TEXT,
    storage_key VARCHAR(80) NOT NULL UNIQUE
        CHECK (storage_key ~ '^[a-f0-9-]+\.(jpg|png|webp|gif)$'),
    mime_type VARCHAR(30) NOT NULL
        CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
    file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_gallery_images_public
    ON public.gallery_images(is_published, sort_order, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_gallery_images_category
    ON public.gallery_images(category, created_at DESC);
