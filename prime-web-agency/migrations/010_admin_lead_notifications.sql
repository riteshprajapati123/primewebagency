-- Admin inbox events for newly saved leads; existing lead rows are untouched.
BEGIN;
CREATE TABLE IF NOT EXISTS public.admin_lead_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT NOT NULL UNIQUE REFERENCES public.leads(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_admin_lead_notifications_unread
  ON public.admin_lead_notifications(read_at, created_at DESC);
INSERT INTO public.admin_lead_notifications(lead_id)
SELECT id FROM public.leads WHERE status='new'
ON CONFLICT (lead_id) DO NOTHING;
COMMIT;
