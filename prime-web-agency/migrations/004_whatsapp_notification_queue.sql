-- Add durable WhatsApp notification settings and queue without changing existing business records.
BEGIN;

CREATE TABLE IF NOT EXISTS public.whatsapp_notification_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    notify_new_leads BOOLEAN NOT NULL DEFAULT TRUE,
    notify_service_inquiries BOOLEAN NOT NULL DEFAULT TRUE,
    notify_project_requests BOOLEAN NOT NULL DEFAULT TRUE,
    notify_attachments BOOLEAN NOT NULL DEFAULT TRUE,
    customer_confirmation BOOLEAN NOT NULL DEFAULT FALSE,
    schedule_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    allowed_days SMALLINT[] NOT NULL DEFAULT ARRAY[1,2,3,4,5,6]::smallint[],
    start_time TIME NOT NULL DEFAULT '09:00',
    end_time TIME NOT NULL DEFAULT '18:00',
    timezone VARCHAR(100) NOT NULL DEFAULT 'Asia/Kolkata',
    recipient_phone VARCHAR(20),
    notification_template_name VARCHAR(120) NOT NULL DEFAULT 'prime_new_lead',
    notification_template_language VARCHAR(20) NOT NULL DEFAULT 'en',
    customer_template_name VARCHAR(120) NOT NULL DEFAULT 'prime_request_received',
    customer_template_language VARCHAR(20) NOT NULL DEFAULT 'en',
    connection_status VARCHAR(24) NOT NULL DEFAULT 'not_tested',
    connection_checked_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT whatsapp_settings_days_check CHECK (allowed_days <@ ARRAY[1,2,3,4,5,6,7]::smallint[]),
    CONSTRAINT whatsapp_settings_timezone_check CHECK (length(timezone) BETWEEN 1 AND 100)
);

INSERT INTO public.whatsapp_notification_settings (id) VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.whatsapp_notification_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT REFERENCES public.leads(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
    attachment_id BIGINT REFERENCES public.lead_attachments(id) ON DELETE CASCADE,
    notification_type VARCHAR(32) NOT NULL CHECK (notification_type IN ('lead', 'service_inquiry', 'project_request', 'customer_confirmation', 'attachment')),
    recipient VARCHAR(20),
    scheduled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'scheduled', 'sending', 'accepted', 'sent', 'delivered', 'read', 'failed', 'skipped')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    max_attempts INTEGER NOT NULL DEFAULT 6 CHECK (max_attempts BETWEEN 1 AND 10),
    last_error TEXT,
    provider_message_id VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((lead_id IS NOT NULL AND project_id IS NULL) OR (lead_id IS NULL AND project_id IS NOT NULL)),
    CHECK (attachment_id IS NULL OR lead_id IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_lead_type
    ON public.whatsapp_notification_queue(lead_id, notification_type)
    WHERE lead_id IS NOT NULL AND attachment_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_attachment_type
    ON public.whatsapp_notification_queue(attachment_id, notification_type)
    WHERE attachment_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_project_type
    ON public.whatsapp_notification_queue(project_id, notification_type)
    WHERE project_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_provider_message
    ON public.whatsapp_notification_queue(provider_message_id)
    WHERE provider_message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_wa_queue_due
    ON public.whatsapp_notification_queue(status, scheduled_at, id)
    WHERE status IN ('pending', 'scheduled', 'failed');

COMMIT;
