-- Additive project workflow, audit history, milestones, private files, and in-app notifications.
BEGIN;

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS progress_percent SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS stage VARCHAR(40) NOT NULL DEFAULT 'request_received',
  ADD COLUMN IF NOT EXISTS estimated_start_date DATE,
  ADD COLUMN IF NOT EXISTS delay_reason TEXT,
  ADD COLUMN IF NOT EXISTS decision_reason TEXT,
  ADD COLUMN IF NOT EXISTS request_key UUID;
CREATE UNIQUE INDEX IF NOT EXISTS idx_projects_request_key ON public.projects(request_key) WHERE request_key IS NOT NULL;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='projects_progress_percent_range') THEN
    ALTER TABLE public.projects ADD CONSTRAINT projects_progress_percent_range CHECK (progress_percent BETWEEN 0 AND 100);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.project_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  actor_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  event_type VARCHAR(40) NOT NULL,
  title VARCHAR(200) NOT NULL,
  note TEXT,
  old_status VARCHAR(40),
  new_status VARCHAR(40),
  old_progress SMALLINT,
  new_progress SMALLINT,
  idempotency_key UUID UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_project_activity_project_created ON public.project_activity(project_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS idx_projects_user_created ON public.projects(user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.project_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  activity_id BIGINT NOT NULL REFERENCES public.project_activity(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ,
  UNIQUE(activity_id,user_id)
);
CREATE INDEX IF NOT EXISTS idx_project_notifications_user_unread ON public.project_notifications(user_id,created_at DESC) WHERE read_at IS NULL;

CREATE TABLE IF NOT EXISTS public.project_milestones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_progress','completed','cancelled')),
  target_date DATE,
  completed_at TIMESTAMPTZ,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(project_id,title)
);
CREATE INDEX IF NOT EXISTS idx_project_milestones_project_order ON public.project_milestones(project_id,sort_order,id);

CREATE TABLE IF NOT EXISTS public.project_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  uploaded_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  original_name VARCHAR(255) NOT NULL,
  storage_key VARCHAR(100) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL CHECK (file_size > 0),
  is_customer_visible BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_project_files_project_created ON public.project_files(project_id,created_at DESC);

COMMIT;
