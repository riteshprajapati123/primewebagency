-- Additive public demo catalog and review visibility controls.
BEGIN;
CREATE TABLE IF NOT EXISTS public.website_demos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  category VARCHAR(100) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  website_url VARCHAR(2048),
  media_key VARCHAR(100),
  media_mime_type VARCHAR(100),
  thumbnail_key VARCHAR(100),
  price_label VARCHAR(160),
  cta_label VARCHAR(80) NOT NULL DEFAULT 'Build a Website Like This',
  is_featured BOOLEAN NOT NULL DEFAULT FALSE,
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  demo_label VARCHAR(120),
  demo_login_url VARCHAR(2048),
  demo_username VARCHAR(160),
  demo_instructions TEXT,
  demo_credentials_public BOOLEAN NOT NULL DEFAULT FALSE,
  demo_account_is_sandbox BOOLEAN NOT NULL DEFAULT FALSE,
  available_until TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_website_demos_public ON public.website_demos(is_published,is_enabled,is_featured,display_order,id);
ALTER TABLE public.approved_reviews ADD COLUMN IF NOT EXISTS is_visible BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE public.approved_reviews ADD COLUMN IF NOT EXISTS is_published BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE public.approved_reviews ADD COLUMN IF NOT EXISTS is_featured BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.approved_reviews ADD COLUMN IF NOT EXISTS reviewer_photo_url VARCHAR(2048);
CREATE INDEX IF NOT EXISTS idx_approved_reviews_visible ON public.approved_reviews(is_approved,attribution_consent,is_published,is_visible,is_featured,sort_order,id);
COMMIT;
