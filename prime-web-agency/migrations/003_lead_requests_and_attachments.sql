-- Extend the existing lead records and add private attachment metadata.
-- Uploaded bytes remain in MEDIA_STORAGE_DIR; no existing files are changed.
BEGIN;

ALTER TABLE public.leads
    ADD COLUMN IF NOT EXISTS lead_reference VARCHAR(24),
    ADD COLUMN IF NOT EXISTS request_key UUID,
    ADD COLUMN IF NOT EXISTS country_code VARCHAR(5),
    ADD COLUMN IF NOT EXISTS local_phone VARCHAR(20),
    ADD COLUMN IF NOT EXISTS service_name_snapshot VARCHAR(200),
    ADD COLUMN IF NOT EXISTS original_price_snapshot NUMERIC(12,2),
    ADD COLUMN IF NOT EXISTS sale_price_snapshot NUMERIC(12,2),
    ADD COLUMN IF NOT EXISTS currency_snapshot VARCHAR(10),
    ADD COLUMN IF NOT EXISTS consent_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS whatsapp_notification_status VARCHAR(24) NOT NULL DEFAULT 'not_configured',
    ADD COLUMN IF NOT EXISTS whatsapp_message_id VARCHAR(255),
    ADD COLUMN IF NOT EXISTS whatsapp_error TEXT,
    ADD COLUMN IF NOT EXISTS whatsapp_attempts INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS whatsapp_last_attempt_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS whatsapp_updated_at TIMESTAMPTZ;

UPDATE public.leads
SET lead_reference = 'PWA-' || LPAD(id::text, 8, '0')
WHERE lead_reference IS NULL;

ALTER TABLE public.leads ALTER COLUMN lead_reference SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_leads_reference ON public.leads(lead_reference);
CREATE UNIQUE INDEX IF NOT EXISTS idx_leads_request_key ON public.leads(request_key) WHERE request_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.lead_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
    storage_key VARCHAR(80) NOT NULL UNIQUE
        CHECK (storage_key ~ '^[a-f0-9-]+\.(jpg|png|webp)$'),
    original_name VARCHAR(180) NOT NULL,
    mime_type VARCHAR(30) NOT NULL
        CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
    file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 2097152),
    whatsapp_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    whatsapp_message_id VARCHAR(255),
    whatsapp_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.lead_attachments
    ADD COLUMN IF NOT EXISTS whatsapp_message_id VARCHAR(255);

CREATE INDEX IF NOT EXISTS idx_lead_attachments_lead ON public.lead_attachments(lead_id, id);

DO $$ BEGIN
    ALTER TABLE public.leads ADD CONSTRAINT leads_whatsapp_status_check
        CHECK (whatsapp_notification_status IN ('not_configured', 'pending', 'sending', 'accepted', 'sent', 'delivered', 'read', 'failed'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

COMMIT;
