    timezone VARCHAR(100) NOT NULL DEFAULT 'Asia/Kolkata' CHECK (length(timezone) BETWEEN 1 AND 100), recipient_phone VARCHAR(20),
    notification_template_name VARCHAR(120) NOT NULL DEFAULT 'prime_new_lead',
    notification_template_language VARCHAR(20) NOT NULL DEFAULT 'en',
    customer_template_name VARCHAR(120) NOT NULL DEFAULT 'prime_request_received',
    customer_template_language VARCHAR(20) NOT NULL DEFAULT 'en',
    connection_status VARCHAR(24) NOT NULL DEFAULT 'not_tested', connection_checked_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ, last_error TEXT, updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
