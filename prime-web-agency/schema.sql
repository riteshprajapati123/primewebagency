
-- PRIME WEB AGENCY
-- PostgreSQL initial schema
-- Application database name: prime-web-agency

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'customer'
        CHECK (role IN ('admin', 'customer')),
    company_name VARCHAR(200),
    phone VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS brand_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(200) NOT NULL DEFAULT 'Prime Web Agency',
    logo_url TEXT,
    favicon_url TEXT,
    tagline TEXT DEFAULT 'Web Development & AI Automation',
    domain_name VARCHAR(255) DEFAULT 'primewebagency.shop',
    email VARCHAR(255),
    phone VARCHAR(30),
    whatsapp_number VARCHAR(30),
    address TEXT,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) UNIQUE,
    description TEXT,
    category VARCHAR(100) NOT NULL DEFAULT 'Web Development',
    price NUMERIC(12,2) NOT NULL DEFAULT 0,
    sale_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    discount_type VARCHAR(20) NOT NULL DEFAULT 'percentage'
        CHECK (discount_type IN ('percentage', 'fixed')),
    discount_value NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (discount_value >= 0),
    offer_badge_text VARCHAR(40),
    sale_start_date DATE,
    sale_end_date DATE,
    CHECK (discount_type <> 'percentage' OR discount_value < 100),
    CHECK (sale_start_date IS NULL OR sale_end_date IS NULL OR sale_end_date >= sale_start_date),
    price_label VARCHAR(100) DEFAULT 'Starting at',
    maintenance_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    billing_label VARCHAR(100) DEFAULT 'one-time',
    features JSONB NOT NULL DEFAULT '[]'::jsonb,
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    service_id BIGINT REFERENCES services(id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    project_type VARCHAR(100),
    status VARCHAR(40) NOT NULL DEFAULT 'pending',
    budget NUMERIC(12,2),
    deadline DATE,
    requirements JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS project_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    sender_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_reference VARCHAR(24) NOT NULL UNIQUE,
    request_key UUID UNIQUE,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(30),
    country_code VARCHAR(5),
    local_phone VARCHAR(20),
    company_name VARCHAR(200),
    service_id BIGINT REFERENCES services(id) ON DELETE SET NULL,
    service_name_snapshot VARCHAR(200),
    original_price_snapshot NUMERIC(12,2),
    sale_price_snapshot NUMERIC(12,2),
    currency_snapshot VARCHAR(10),
    message TEXT,
    source VARCHAR(100) DEFAULT 'website',
    status VARCHAR(40) NOT NULL DEFAULT 'new',
    consent_at TIMESTAMPTZ,
    whatsapp_notification_status VARCHAR(24) NOT NULL DEFAULT 'not_configured'
        CHECK (whatsapp_notification_status IN ('not_configured','pending','sending','accepted','sent','delivered','read','failed')),
    whatsapp_message_id VARCHAR(255),
    whatsapp_error TEXT,
    whatsapp_attempts INTEGER NOT NULL DEFAULT 0,
    whatsapp_last_attempt_at TIMESTAMPTZ,
    whatsapp_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_leads_request_key ON leads(request_key) WHERE request_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS lead_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    storage_key VARCHAR(80) NOT NULL UNIQUE
        CHECK (storage_key ~ '^[a-f0-9-]+\.(jpg|png|webp)$'),
    original_name VARCHAR(180) NOT NULL,
    mime_type VARCHAR(30) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp')),
    file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 2097152),
    whatsapp_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    whatsapp_message_id VARCHAR(255),
    whatsapp_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_lead_attachments_lead ON lead_attachments(lead_id,id);

CREATE TABLE IF NOT EXISTS analytics_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    event_type VARCHAR(100) NOT NULL,
    page_url TEXT,
    session_id VARCHAR(255),
    referrer TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    visitor_id VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS portfolio_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(220) UNIQUE,
    description TEXT,
    category VARCHAR(100),
    image_url TEXT,
    project_url TEXT,
    technologies JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Public and private media metadata. File contents are stored outside public/.
CREATE TABLE IF NOT EXISTS gallery_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    alt_text VARCHAR(300) NOT NULL DEFAULT '',
    category VARCHAR(100) NOT NULL DEFAULT 'General',
    caption TEXT,
    storage_key VARCHAR(80) NOT NULL UNIQUE
        CHECK (storage_key ~ '^[a-f0-9-]+\.(jpg|png|webp|gif)$'),
    mime_type VARCHAR(30) NOT NULL
        CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
    file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_gallery_images_public
    ON gallery_images(is_published, sort_order, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_gallery_images_category
    ON gallery_images(category, created_at DESC);

CREATE TABLE IF NOT EXISTS ai_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    business_name VARCHAR(200),
    system_prompt TEXT,
    model_name VARCHAR(100) DEFAULT 'gpt-4o-mini',
    temperature NUMERIC(3,2) DEFAULT 0.40,
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS whatsapp_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    provider VARCHAR(50) NOT NULL DEFAULT 'meta',
    phone_number VARCHAR(30),
    phone_number_id VARCHAR(255) UNIQUE,
    business_account_id VARCHAR(255),
    access_token_encrypted TEXT,
    webhook_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_connected BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(150),
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(255),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, phone)
);

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    contact_id BIGINT REFERENCES contacts(id) ON DELETE SET NULL,
    whatsapp_account_id BIGINT REFERENCES whatsapp_accounts(id) ON DELETE SET NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'open',
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    last_message_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL
        REFERENCES conversations(id) ON DELETE CASCADE,
    direction VARCHAR(20) NOT NULL
        CHECK (direction IN ('inbound', 'outbound')),
    message_type VARCHAR(40) NOT NULL DEFAULT 'text',
    content TEXT,
    provider_message_id VARCHAR(255),
    delivery_status VARCHAR(40) DEFAULT 'pending',
    ai_generated BOOLEAN NOT NULL DEFAULT FALSE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS automations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    trigger_type VARCHAR(100) NOT NULL,
    trigger_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    action_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ai_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    conversation_id BIGINT REFERENCES conversations(id) ON DELETE SET NULL,
    model_name VARCHAR(100),
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    estimated_cost NUMERIC(12,6) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS handoffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL
        REFERENCES conversations(id) ON DELETE CASCADE,
    reason TEXT,
    status VARCHAR(40) NOT NULL DEFAULT 'pending',
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(150) NOT NULL,
    entity_type VARCHAR(100),
    entity_id VARCHAR(100),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Performance indexes
CREATE INDEX IF NOT EXISTS idx_projects_user
    ON projects(user_id);
CREATE INDEX IF NOT EXISTS idx_projects_status
    ON projects(status);
CREATE INDEX IF NOT EXISTS idx_leads_created
    ON leads(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_analytics_created
    ON analytics_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_analytics_event
    ON analytics_events(event_type);
CREATE INDEX IF NOT EXISTS idx_messages_conversation
    ON messages(conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_conversations_user
    ON conversations(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created
    ON audit_logs(created_at DESC);

