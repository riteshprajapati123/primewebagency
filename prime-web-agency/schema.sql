CREATE TABLE IF NOT EXISTS whatsapp_notification_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, lead_id BIGINT REFERENCES leads(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE, attachment_id BIGINT REFERENCES lead_attachments(id) ON DELETE CASCADE,
    notification_type VARCHAR(32) NOT NULL CHECK (notification_type IN ('lead','service_inquiry','project_request','customer_confirmation','attachment')), recipient VARCHAR(20), scheduled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','scheduled','sending','accepted','sent','delivered','read','failed','skipped')), attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0), max_attempts INTEGER NOT NULL DEFAULT 6 CHECK (max_attempts BETWEEN 1 AND 10),
    last_error TEXT, provider_message_id VARCHAR(255), created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((lead_id IS NOT NULL AND project_id IS NULL) OR (lead_id IS NULL AND project_id IS NOT NULL)),
    CHECK (attachment_id IS NULL OR lead_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_lead_type ON whatsapp_notification_queue(lead_id,notification_type) WHERE lead_id IS NOT NULL AND attachment_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_attachment_type ON whatsapp_notification_queue(attachment_id,notification_type) WHERE attachment_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_project_type ON whatsapp_notification_queue(project_id,notification_type) WHERE project_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_wa_queue_provider_message ON whatsapp_notification_queue(provider_message_id) WHERE provider_message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_wa_queue_due ON whatsapp_notification_queue(status,scheduled_at,id) WHERE status IN ('pending','scheduled','failed');

