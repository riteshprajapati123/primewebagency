CREATE TABLE IF NOT EXISTS whatsapp_notification_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1), enabled BOOLEAN NOT NULL DEFAULT TRUE,
    notify_new_leads BOOLEAN NOT NULL DEFAULT TRUE, notify_service_inquiries BOOLEAN NOT NULL DEFAULT TRUE,
    notify_project_requests BOOLEAN NOT NULL DEFAULT TRUE, notify_attachments BOOLEAN NOT NULL DEFAULT TRUE,
    customer_confirmation BOOLEAN NOT NULL DEFAULT FALSE, schedule_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    allowed_days SMALLINT[] NOT NULL DEFAULT ARRAY[1,2,3,4,5,6]::smallint[] CHECK (allowed_days <@ ARRAY[1,2,3,4,5,6,7]::smallint[]),
